const WILD_ZONE_COLOR = '#49ea82';

const hotspotFor = (target: string, outline: Array<Point>): Hotspot => {
  const xs = outline.map(([x]) => x);
  const ys = outline.map(([, y]) => y);
  const x = Math.min(...xs);
  const y = Math.min(...ys);

  return {
    x,
    y,
    width: Math.max(...xs) - x,
    height: Math.max(...ys) - y,
    shape: outline,
    display: 'always',
    color: WILD_ZONE_COLOR,
    target,
  };
};

