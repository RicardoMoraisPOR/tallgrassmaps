const stock = (...names: Array<string>): Array<ShopItem> =>
  names.map((name) => ({ name, price: PRICES[name] }));

const ALL = ['red', 'blue', 'yellow'];

const mart = (
  path: string,
  games: Array<string>,
  ...names: Array<string>
): Shop => ({
  id: `${path}:${games.join()}`,
  building: 'Poké Mart',
  name: 'Poké Mart',
  path,
  x: 1,
  y: 5,
  stock: stock(...names),
  games,
});

const counter = (
  path: string,
  floor: string,
  name: string,
  x: number,
  y: number,
  ...names: Array<string>
): Shop => ({
  id: `${path}:${floor}:${x}`,
  building: 'Celadon Dept. Store',
  name,
  path,
  floor,
  x,
  y,
  stock: stock(...names),
  games: ALL,
});

